/** 1 -> "1er" / "1st"; returns { n, suffix }. */
export function ordinalParts(n, lang = current) {
  n = Math.max(1, n | 0);
  if (lang === 'fr') return { n, suffix: n === 1 ? 'er' : 'e' };
  const v = n % 100;
  const s = ['th', 'st', 'nd', 'rd'];
  return { n, suffix: s[(v - 20) % 10] || s[v] || s[0] };
}
export function ordinal(n, lang = current) { const o = ordinalParts(n, lang); return `${o.n}${o.suffix}`; }

export function formatTime(t) {
  if (t == null || !isFinite(t)) return '--:--.--';
  const m = Math.floor(t / 60), s2 = t - m * 60, ss = Math.floor(s2), cs = Math.floor((s2 - ss) * 100);
  return `${m}:${String(ss).padStart(2, '0')}.${String(cs).padStart(2, '0')}`;
}

/** Escape player-provided or data-driven text before it reaches innerHTML. */
export function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

