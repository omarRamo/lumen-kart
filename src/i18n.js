let current = 'en';
const listeners = new Set();

/** French when the device language is French, English otherwise. */
export function detectLanguage(nav = globalThis.navigator) {
  const list = [];
  try {
    if (nav && Array.isArray(nav.languages)) list.push(...nav.languages);
    if (nav && nav.language) list.unshift(nav.language);
  } catch { /* ignore */ }
  const first = String(list.find(Boolean) || '').toLowerCase();
  return first.startsWith('fr') ? 'fr' : 'en';
}

/** 'auto' (or anything unknown) resolves from the device. */
export function resolveLanguage(pref, nav) {
  return LANGS.includes(pref) ? pref : detectLanguage(nav);
}

export function getLanguage() { return current; }

export function setLanguage(lang) {
  const next = LANGS.includes(lang) ? lang : 'en';
  if (next === current) return current;
  current = next;
  try { if (globalThis.document?.documentElement) globalThis.document.documentElement.lang = next; } catch { /* ignore */ }
  for (const fn of [...listeners]) { try { fn(next); } catch (e) { console.error('[i18n] listener', e); } }
  return current;
}

export function onLanguageChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

/** French typography: no-break spaces before high punctuation and inside guillemets, so a lone "!" or ":"
 *  never wraps onto its own line on a phone (narrow NBSP before ! ? ;, NBSP before : and inside « »). */
export function frenchSpacing(s) {
  return String(s).replace(/ ([!?;])/g, '\u202f$1').replace(/ :/g, '\u00a0:').replace(/« /g, '«\u00a0').replace(/ »/g, '\u00a0»');
}
const typo = (s, lang) => (lang === 'fr' && s ? frenchSpacing(s) : s);

export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.en;
  let s = table[key];
  if (s == null) s = STRINGS.en[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return typo(s, current);
}

